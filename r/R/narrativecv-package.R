#' narrativecv: map narrative CV sections to evidence in open research infrastructures
#'
#' Narrative CVs, such as the Royal Society's Résumé for Researchers (R4RI) or
#' the Spanish Currículum Vitae Abreviado (CVA), ask researchers to describe
#' contributions that metrics miss. Some of them leave traces in open
#' infrastructures; many do not. narrativecv applies an open, versioned
#' crosswalk to show, section by section, what ORCID, OpenAlex, DataCite and
#' the OpenAIRE Graph can document, with the evidence type, coverage and
#' limitations of each source, and which sections only the researcher's own
#' narrative can support.
#'
#' Start with [narrative_cv()], or [nc_example_evidence()] to work offline.
#' See `vignette("narrativecv")` for the method and its limits.
#'
#' @keywords internal
